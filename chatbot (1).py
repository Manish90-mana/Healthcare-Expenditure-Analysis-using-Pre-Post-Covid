def chatbot():

    print("\n Healthcare Burden Prediction Chatbot")
    print("Enter patient details:\n")

    # User Inputs
    age = int(input("Age: "))
    rxexp = float(input("Prescription Expense: "))
    insurc = int(input("Insurance Category (INSURC): "))
    povcat = int(input("Poverty Category (POVCAT): "))
    sex = int(input("Sex (1=Male, 2=Female): "))
    race = int(input("Race (1–6): "))
    empst = int(input("Employment (0/1): "))
    zip_code = input("ZIP Code: ")

    X = prepare_input(age, rxexp, insurc, povcat, sex, race, empst)

    prob = model.predict_proba(X)[0][1]

    if prob > 0.7:
        risk = "HIGH RISK"
    elif prob > 0.4:
        risk = "MEDIUM RISK"
    else:
        risk = " LOW RISK"

    print("\n RESULT:")
    print(f"{risk} (Probability: {prob:.2f})")

    print("\n Key Factors Influencing Risk:")

    if rxexp > 10000:
        print(" - High medical expenses increase risk")
    elif rxexp < 2000:
        print(" - Low medical expenses reduce risk")

    if povcat == 1:
        print(" - Low income category increases financial burden")

    if insurc == 3:
        print(" - Lack of insurance increases risk")

    if empst == 0:
        print(" - Unemployment contributes to financial stress")

    if age > 60:
        print(" - Higher age may increase healthcare needs")
    print("\n💡 Recommendations:")

    if prob > 0.7:
        print(" - Consider financial assistance programs")
        print(" - Explore government health schemes")
        print(" - Reduce unnecessary medical expenses")

    elif prob > 0.4:
        print(" - Monitor healthcare spending")
        print(" - Ensure insurance coverage")

    else:
        print(" - Maintain healthy lifestyle")
        print(" - Continue regular checkups")

    print("\n Nearby Support Resources:")


    resources = get_resources(zip_code)

    if resources:
        for r in resources:
            print(f" - {r['name']} ({r['type']}) |  {r['phone']}")
    else:
        print(" No local resources found for this ZIP code")

chatbot()

